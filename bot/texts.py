def crystals_word(n: int) -> str:
    n = abs(int(n)) % 100
    if 11 <= n <= 14:
        return "кристаллов"
    last = n % 10
    if last == 1:
        return "кристалл"
    if 2 <= last <= 4:
        return "кристалла"
    return "кристаллов"
