EN_PHRASES = ["no clothes"]

# Дефис — не граница слова для \b (не \w, но и не пробел), поэтому дефисованные словосочетания
# вроде "sex-photo" или "ass-shot" всё равно матчатся на "sex"/"ass" по обычным \b-границам — это
# и нужно, иначе список можно обойти простой дефисацией любого запрещённого слова. Единственное
# исключение — легитимные составные слова вроде "gore-tex": они не запрещены сами по себе, поэтому
# целиком вырезаются из текста до проверки через ALLOWED_COMPOUNDS, а не через ослабление границ.
ALLOWED_COMPOUNDS = ["gore-tex", "goretex"]

_RE = re.compile(
    r"\b(?:" + "|".join(map(re.escape, RU_STEMS + EN_STEMS)) + r")"
    r"|\b(?:" + "|".join(map(re.escape, RU_WORDS + EN_WORDS)) + r")\b"
    r"|(?:" + "|".join(map(re.escape, RU_PHRASES + EN_PHRASES)) + r")"
)


def _normalize(text: str) -> str:
    t = text.lower().replace("ё", "е")
    for c in ALLOWED_COMPOUNDS:
        t = t.replace(c, " ")
    return t


def is_allowed(text: str) -> bool:
    return _RE.search(_normalize(text)) is None


# Свой промпт видео не режем по взрослым словам. Несовершеннолетних не пускаем.
_MINOR_STEMS = (
    "малолет", "несовершеннолет", "школьниц", "школьник", "ребен",
    "подрост", "малыш", "младен", "детск", "underage", "loli",
)
_MINOR_WORDS = (
    "child", "children", "kid", "kids", "teen", "teens", "minor", "minors",
    "дети", "детей", "детям", "детьми",
)
_MINOR_RE = re.compile(
    r"\b(?:" + "|".join(map(re.escape, _MINOR_STEMS)) + r")"
    r"|\b(?:" + "|".join(map(re.escape, _MINOR_WORDS)) + r")\b"
)


def mentions_minor(text: str) -> bool:
    return _MINOR_RE.search(_normalize(text)) is not None
