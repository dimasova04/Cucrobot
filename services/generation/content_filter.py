# (?!-tex) на группе *_WORDS: "\b" срабатывает и на дефисе (не только на пробеле), так что без этого
# исключения "gore" из EN_WORDS ловил бы безобидный "gore-tex jacket" (проверено скриптом).
_RE = re.compile(
    r"\b(?:" + "|".join(map(re.escape, RU_STEMS + EN_STEMS)) + r")"
    r"|\b(?:" + "|".join(map(re.escape, RU_WORDS + EN_WORDS)) + r")\b(?!-tex)"
    r"|(?:" + "|".join(map(re.escape, RU_PHRASES + EN_PHRASES)) + r")"
)


def is_allowed(text: str) -> bool:
    return _RE.search(text.lower().replace("ё", "е")) is None
