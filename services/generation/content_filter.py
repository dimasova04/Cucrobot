# Три класса правил:
#   *_STEMS   — совпадение по началу слова (\b + стем); только стемы, с которых не начинаются
#               обычные безобидные слова;
#   *_WORDS   — точные словоформы (\b + слово + \b);
#   *_PHRASES — подстроки.
# Текст перед проверкой приводится к нижнему регистру, ё -> е.
#
# Аудит оставленных стемов (проверено venv-скриптом против списка безобидных слов):
#   RU_STEMS:
#     раздет   — раздетый/раздеть; безобидных слов с этим началом не найдено.
#     нагиш    — нагишом; безобидных слов с этим началом не найдено.
#     эрот     — эротика; безобидных слов с этим началом не найдено.
#     порно    — безобидных слов с этим началом не найдено (порножурнал блокируется намеренно).
#     интим    — интимный; безобидных слов с этим началом не найдено.
#     оргазм   — безобидных слов с этим началом не найдено (оргазмический блокируется намеренно).
#     ебл, ебат, хуй, пизд, минет — обсценная лексика; безобидных слов с этим началом нет.
#     сиськ    — безобидных слов с этим началом не найдено.
#     задниц   — безобидных слов с этим началом не найдено.
#     ягодиц   — безобидных слов с этим началом не найдено.
#     бикини   — безобидных слов с этим началом не найдено.
#     лифчик   — безобидных слов с этим началом не найдено.
#     трусик   — безобидных слов с этим началом не найдено.
#     чулк     — безобидных слов с этим началом не найдено.
#     бдсм     — безобидных слов с этим началом не найдено.
#     изнасил  — изнасилование; безобидных слов с этим началом не найдено.
#     убий     — убийство/убийца; безобидных слов с этим началом не найдено.
#   Удалены (коллизии с обычными словами): секс (секстант, секстет), стринг (стрингер),
#   обнажен (обнажение зуба) — перенесены в RU_WORDS как точные словоформы.
#   EN_STEMS:
#     nude     — naked; "nude" не является подстрокой "nudge" (n-u-d-g-e), поэтому \bnude не
#                совпадает с ним (проверено скриптом: "nudge him gently" не блокируется).
#     naked, topless, undress, lingerie, underwear, bikini, panties — безобидных коллизий не найдено.
#     erotic, porn, nsfw, orgasm — безобидных коллизий не найдено ("orgasmic" блокируется намеренно).
#     fuck, nipple, blowjob, bdsm — безобидных коллизий не найдено.
#   Удалены (коллизии с обычными словами): rape (rapeseed), gore (gore-tex), intimate (intimated),
#   boob (booby), pussy (pussycat), blood (bloodhound) — перенесены в EN_WORDS как точные словоформы.

